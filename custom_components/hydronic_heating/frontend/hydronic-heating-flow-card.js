class HydronicHeatingFlowCard extends HTMLElement {
  constructor() {
    super();
    this.attachShadow({ mode: "open" });
    this._layoutKey = "";
    this._width = 0;
  }

  static getStubConfig() {
    return { floors: [] };
  }

  setConfig(config) {
    if (!config || typeof config !== "object") throw new Error("Invalid configuration");
    this._config = config;
    this._layoutKey = "";
    if (this._hass) this._render();
  }

  set hass(hass) {
    this._hass = hass;
    this._render();
  }

  static async getConfigElement() {
    await loadForm();
    return document.createElement(`${TAG}-editor`);
  }

  getCardSize() {
    // Units of 50 px: the scheme, then the phases and the texts.
    const opt = options(this._config);
    const g = GEOMETRY[opt.layout];
    const rows = this._layoutRows?.length || this._config?.floors?.length || 1;
    const px = rows * g.row + g.boiler + (opt.phases ? 70 : 0) + (opt.status ? 30 : 0)
      + (opt.now || opt.upcoming ? 120 : 0);
    return Math.ceil(px / 50);
  }

  getGridOptions() {
    return { columns: "full", rows: "auto" };
  }

  connectedCallback() {
    this._timer = window.setInterval(() => this._tick(), 1000);
    if (!this._observer && "ResizeObserver" in window) {
      this._observer = new ResizeObserver((entries) => {
        const width = Math.round(entries[0].contentRect.width);
        if (Math.abs(width - this._width) > 8) {
          this._width = width;
          this._render();
        }
      });
      this._observer.observe(this);
    }
  }

  disconnectedCallback() {
    window.clearInterval(this._timer);
    if (this._observer) {
      this._observer.disconnect();
      this._observer = undefined;
    }
  }

  // --- helpers -------------------------------------------------------------

  get _t() {
    const lang = (this._hass?.locale?.language || this._hass?.language || "en").slice(0, 2);
    return TEXTS[lang] || TEXTS.en;
  }

  _state(entityId) {
    return entityId ? this._hass?.states?.[entityId] : undefined;
  }

  _format(entityId) {
    const state = this._state(entityId);
    if (!state || ["unknown", "unavailable"].includes(state.state)) return "–";
    try {
      return this._hass.formatEntityState(state);
    } catch (err) {
      return state.state;
    }
  }

  _rooms() {
    const floors = Array.isArray(this._config?.floors) ? this._config.floors : [];
    return floors.flatMap((floor) => floor.rooms || []);
  }

  _moreInfo(entityId) {
    if (!entityId) return;
    const event = new Event("hass-more-info", { bubbles: true, composed: true });
    event.detail = { entityId };
    this.dispatchEvent(event);
  }

  // --- layout --------------------------------------------------------------

  _rows(width) {
    const slots = Math.max(1, Math.floor((width - LEFT - 8) / MIN_SLOT));
    const rows = [];
    for (const floor of this._config.floors || []) {
      const rooms = floor.rooms || [];
      for (let i = 0; i < Math.max(rooms.length, 1); i += slots) {
        rows.push({
          floor: i === 0 ? floor.name || "" : "",
          ventilation: i === 0 ? floor.ventilation : undefined,
          rooms: rooms.slice(i, i + slots),
        });
      }
    }
    return { rows, slots };
  }

  _build(g, interactive) {
    const width = Math.max(300, this._width || this.clientWidth || 900);
    const { rows, slots } = this._rows(width);
    const slot = Math.max(MIN_SLOT, (width - LEFT - 8) / Math.max(1, Math.min(slots,
      Math.max(...rows.map((r) => r.rooms.length), 1))));
    const height = rows.length * g.row + g.boiler;
    const boilerY = rows.length * g.row;
    const parts = [];
    // A band across the floor while it is aired (FR-WIN-07), under everything else.
    rows.forEach((_, r) => {
      parts.push(`<rect class="band" data-band="${r}" x="${LEFT - 10}" y="${r * g.row + 2}"
        width="${width - LEFT + 6}" height="${g.row - 4}" rx="10"/>`);
    });
    // Risers in segments: segment r carries the water of row r and the rows above.
    rows.forEach((_, r) => {
      const last = r === rows.length - 1;
      const below = last ? boilerY + g.caseY : (r + 1) * g.row + g.supply;
      parts.push(this._pipe(`M${SUPPLY_X} ${below} V${r * g.row + g.supply}`, "supply", `riser-s-${r}`));
      const under = last ? boilerY + g.caseY : (r + 1) * g.row + g.ret;
      parts.push(this._pipe(`M${RETURN_X} ${r * g.row + g.ret} V${under}`, "return", `riser-r-${r}`));
    });
    rows.forEach((row, r) => {
      const y0 = r * g.row;
      if (row.floor) {
        // Tap the floor to air it (FR-WIN-07); the text shows until when it airs.
        const airable = interactive && row.ventilation;
        const role = airable ? ` role="button" tabindex="0"` : "";
        parts.push(`<text class="floor${airable ? " airable" : ""}" data-floor="${r}"
          x="${LEFT}" y="${y0 + g.floor}"${role}>${esc(row.floor)}</text>`);
      }
      if (!row.rooms.length) return;
      const xs = row.rooms.map((_, i) => LEFT + slot * (i + 0.5));
      const rw = Math.min(64, slot - 30);
      // Main pipes in segments: segment i feeds radiator i and the ones behind it.
      xs.forEach((x, i) => {
        const from = i === 0 ? SUPPLY_X : xs[i - 1] - rw / 2 + 8;
        parts.push(this._pipe(`M${from} ${y0 + g.supply} H${x - rw / 2 + 8}`, "supply", `main-s-${r}-${i}`));
        const to = i === 0 ? RETURN_X : xs[i - 1] + rw / 2 - 8;
        parts.push(this._pipe(`M${x + rw / 2 - 8} ${y0 + g.ret} H${to}`, "return", `main-r-${r}-${i}`));
      });
      row.rooms.forEach((room, i) => {
        parts.push(this._room(g, room, xs[i], y0, rw, slot, `${r}-${i}`, interactive));
      });
    });
    parts.push(this._boiler(g, boilerY, interactive));
    return { svg: `<svg viewBox="0 0 ${width} ${height}" width="${width}" height="${height}"
      role="img">${parts.join("")}</svg>`, rows };
  }

  _pipe(d, kind, id) {
    return `<path class="pipe ${kind}" d="${d}"/>` +
      `<path class="flow ${kind}" data-flow="${id}" d="${d}"/>`;
  }

  _room(g, room, cx, y0, rw, slot, id, interactive) {
    const left = cx - rw / 2;
    const sx = left + 8;
    const rx = left + rw - 8;
    const top = y0 + g.body;
    const bottom = top + g.bodyH;
    const fins = [];
    for (let x = left + 10; x < left + rw - 6; x += 10) {
      fins.push(`<line x1="${x}" y1="${top + 4}" x2="${x}" y2="${bottom - 4}"/>`);
    }
    const name = clip(room.name || "", Math.floor(slot / 7.2));
    const vy = y0 + g.valve;
    // The window icon over the right side of the radiator (the pipe temperature is
    // left of the valve), above the frame; the flame of a calling room 2 px higher.
    const wx = left + rw - 13;
    const wy = top - g.icon;
    return `
      <g class="room" data-room="${id}"${interactive ? ` tabindex="0" role="button"` : ""}
         aria-label="${esc(room.name || "")}">
        ${this._pipe(`M${sx} ${y0 + g.supply} V${top}`, "supply", `branch-s-${id}`)}
        ${this._pipe(`M${rx} ${bottom} V${y0 + g.ret}`, "return", `branch-r-${id}`)}
        <rect class="frame" x="${left - 3}" y="${top - 3}" width="${rw + 6}" height="${g.bodyH + 6}"
              rx="7"/>
        <g class="radiator" data-radiator="${id}">
          <rect class="body" x="${left}" y="${top}" width="${rw}" height="${g.bodyH}" rx="5"/>
          ${fins.join("")}
        </g>
        <g transform="translate(${left + rw - 10} ${top - g.icon - 2}) scale(0.62)">
          <path class="badge" d="${FIRE}"/></g>
        <g class="win"><rect x="${wx}" y="${wy}" width="12" height="11" rx="1.5"/>
          <line x1="${wx + 6}" y1="${wy}" x2="${wx + 6}" y2="${wy + 11}"/>
          <line x1="${wx}" y1="${wy + 5.5}" x2="${wx + 12}" y2="${wy + 5.5}"/></g>
        <rect class="dbar-bg" x="${left + 2}" y="${y0 + g.bar}" width="${rw - 4}" height="4" rx="2"/>
        <rect class="dbar" data-dbar="${id}" x="${left + 2}" y="${y0 + g.bar}" width="0" height="4"
              rx="2"/>
        <text class="pipe-t" data-pipe="${id}" x="${sx - 11}" y="${vy + 10}" text-anchor="end"></text>
        <g class="vsym unknown" data-vsym="${id}" transform="translate(${sx} ${vy + 6})">
          <circle r="7.5"/><line class="stem" x1="0" y1="-5" x2="0" y2="5"/></g>
        <text class="label" x="${cx}" y="${y0 + g.label}" text-anchor="middle">${esc(name)}</text>
        <text class="info" data-info="${id}" x="${cx}" y="${y0 + g.info}"
              text-anchor="middle"></text>
      </g>`;
  }

  _boiler(g, y, interactive) {
    const [label, temp, state] = g.textY;
    const role = interactive ? ` tabindex="0" role="button"` : "";
    return `
      <g class="boiler" data-boiler${role} aria-label="${this._t.boiler}">
        <rect class="glow" x="2" y="${y + g.caseY - 6}" width="${g.caseW + 12}"
              height="${g.caseH + 12}" rx="16"/>
        <rect class="case" x="8" y="${y + g.caseY}" width="${g.caseW}" height="${g.caseH}" rx="12"/>
        <g transform="translate(${g.flameX} ${y + g.flameY}) scale(${g.flame})">
          <path class="flame" d="${FIRE}"/></g>
        <text class="label" x="${g.textX}" y="${y + label}">${this._t.boiler}</text>
        <text class="info" data-boiler-temp x="${g.textX}" y="${y + temp}"></text>
        <text class="info bstate" data-boiler-state x="${g.textX}" y="${y + state}"></text>
      </g>`;
  }

  // --- render --------------------------------------------------------------

  _render() {
    if (!this._config || !this._hass) return;
    if (!this._rooms().length) {
      this.shadowRoot.innerHTML = `<style>${STYLE}</style>
        <ha-card><div class="missing">${this._t.missing}</div></ha-card>`;
      this._layoutKey = "";
      return;
    }
    const width = Math.round(this._width || this.clientWidth || 900);
    const key = `${width}|${JSON.stringify(this._config)}|${this._t.boiler}`;
    if (key !== this._layoutKey) {
      this._layoutKey = key;
      const opt = options(this._config);
      const { svg, rows } = this._build(GEOMETRY[opt.layout], opt.interactive);
      this._layoutRows = rows;
      const t = this._t;
      const title = this._config.title ? `<div class="title">${esc(this._config.title)}</div>` : "<div></div>";
      const head = this._config.title || opt.outdoor
        ? `<div class="head">${title}${opt.outdoor ? `<div class="outdoor" data-outdoor></div>` : ""}</div>`
        : "";
      const phases = opt.phases
        ? `<div class="phases">
            ${["idle", "valves", "firing", "overrun"]
              .map((s) => `<div class="step ${s}" data-step="${s}">${t.phases[s]}</div>`)
              .join("")}
          </div>
          <div class="status"><span class="chip" data-chip hidden></span>
            <span class="countdown" data-countdown></span></div>`
        : "";
      const status = opt.status
        ? `<div class="statusline" data-sl><span class="dot"></span><b data-sl-title></b>
            <span data-sl-text></span></div>`
        : "";
      const columns = [
        opt.now ? `<div><h4>${t.now}</h4><div data-now></div></div>` : "",
        opt.upcoming ? `<div><h4>${t.next}</h4><ul data-next></ul></div>` : "",
      ].filter(Boolean);
      const texts = columns.length
        ? `<div class="texts${columns.length === 1 ? " single" : ""}">${columns.join("")}</div>`
        : "";
      const tap = opt.tapAction ? ` tappable" tabindex="0" role="button` : "";
      this.shadowRoot.innerHTML = `
        <style>${STYLE}</style>
        <ha-card class="${opt.layout}${tap}" style="--hh-hot: var(--deep-orange-color, #ff6f22);
          --hh-cold: var(--blue-color, #2196f3); --hh-open: var(--cyan-color, #00bcd4);
          --hh-moving: var(--amber-color, #ffc107); --hh-idle: var(--grey-color, #9e9e9e);">
          <div class="banner" data-banner hidden></div>
          ${head}
          ${svg}
          ${status}
          ${phases}
          ${texts}
        </ha-card>`;
      this._bind(opt);
    }
    this._update();
  }

  _bind(opt) {
    const root = this.shadowRoot;
    // A tapped part does not also run the action of the card.
    const press = (el, run) => {
      el?.addEventListener("click", (ev) => {
        ev.stopPropagation();
        run();
      });
      el?.addEventListener("keydown", (ev) => {
        if (ev.key !== "Enter" && ev.key !== " ") return;
        ev.stopPropagation();
        ev.preventDefault();
        run();
      });
    };
    if (opt.tapAction) {
      // A standard action of Home Assistant (navigate, more-info…), FR-UI-25.
      const config = { tap_action: opt.tapAction };
      press(root.querySelector("ha-card"), () =>
        this.dispatchEvent(new CustomEvent("hass-action", {
          detail: { config, action: "tap" }, bubbles: true, composed: true,
        })),
      );
    }
    if (!opt.interactive) return;
    const rooms = this._layoutRooms();
    root.querySelectorAll("[data-room]").forEach((el) => {
      const room = rooms[el.dataset.room];
      press(el, () => this._moreInfo(room?.climate));
    });
    root.querySelectorAll("[data-floor]").forEach((el) => {
      const row = (this._layoutRows || [])[el.dataset.floor];
      if (!row?.ventilation) return;
      press(el, () => {
        const on = this._state(row.ventilation)?.state === "on";
        this._hass.callService("switch", on ? "turn_off" : "turn_on", {
          entity_id: row.ventilation,
        });
      });
    });
    press(root.querySelector("[data-boiler]"),
      () => this._moreInfo(this._config.reason || this._config.boiler));
  }

  _layoutRooms() {
    const map = {};
    (this._layoutRows || []).forEach((row, r) =>
      row.rooms.forEach((room, i) => {
        map[`${r}-${i}`] = room;
      }),
    );
    return map;
  }

  _update() {
    const root = this.shadowRoot;
    const cfg = this._config;
    const t = this._t;
    const boiler = this._state(cfg.boiler);
    const reason = this._state(cfg.reason);
    const code = reason?.state || "idle";
    const phase = boiler?.attributes?.phase || "idle";
    const pump = phase === "firing" || phase === "overrun";
    const actual = this._state(cfg.actual);
    const burning = actual ? actual.state === "on" : boiler?.state === "on" && phase === "firing";
    const slow = phase === "overrun";
    const flowing = {};

    for (const [id, room] of Object.entries(this._layoutRooms())) {
      const valve = this._state(room.valve);
      const vstate = valve?.state || "unknown";
      const flows = pump && FLOWING_VALVES.has(vstate);
      flowing[id] = flows;
      const climate = this._state(room.climate);
      const problem = this._state(room.problem);
      const windowState = climate?.attributes?.window_state;
      const airing = Boolean(windowState) && windowState !== "closed";
      const off = climate?.state === "off";
      const valveFault = (problem?.attributes?.valve_failures || []).length > 0;
      const sensorFault = problem?.attributes?.sensor_failure
        || (problem?.attributes?.invalid_sensors || []).length > 0;

      // Ball valve: the lever along the pipe is open, across it closed, it turns in a
      // loop while the head moves; at rest an open valve without current is an empty
      // ring, cyan only while water flows.
      let vs = { open: "open", closed: "closed", opening: "opening", closing: "closing" }[vstate]
        || (vstate === "mixed" ? "closing" : "unknown");
      if (vs === "open" && !pump) vs = "rest";
      root.querySelector(`[data-vsym="${id}"]`)
        ?.setAttribute("class", `vsym ${vs}${valveFault ? " vfault" : ""}`);

      // Radiator: bright while water flows, faded while it still gives heat.
      const rad = root.querySelector(`[data-radiator="${id}"]`);
      const body = rad?.querySelector("rect.body");
      const last = Date.parse(valve?.attributes?.last_flow);
      const age = Number.isFinite(last) ? (Date.now() - last) / 60000 : Infinity;
      let rcls = "radiator";
      if (body) body.style.opacity = "";
      if (flows) rcls += " hot";
      else if (age >= 0 && age < RESIDUAL_MIN) {
        rcls += " resid";
        if (body) body.style.opacity = String(0.22 + 0.5 * (1 - age / RESIDUAL_MIN));
      }
      rad?.setAttribute("class", rcls);
      const pipe = Number(this._state(room.pipe)?.state);
      const pipeEl = root.querySelector(`[data-pipe="${id}"]`);
      if (pipeEl) pipeEl.textContent = room.pipe && Number.isFinite(pipe) ? `${this._num(pipe)} °C` : "";

      // A room that calls the boiler, a fault, airing.
      const demandState = this._state(room.demand);
      const demand = Number(demandState?.state);
      const threshold = Number(demandState?.attributes?.call_threshold ?? cfg.call_threshold ?? 50);
      const calling = !off && !airing && demand >= threshold;
      root.querySelector(`[data-room="${id}"]`)?.setAttribute("class", ["room",
        calling && "calling", problem?.state === "on" && "fault", airing && "airing"]
        .filter(Boolean).join(" "));
      const bar = root.querySelector(`[data-dbar="${id}"]`);
      if (bar) {
        const full = Number(bar.previousElementSibling.getAttribute("width"));
        const share = Number.isFinite(demand) ? Math.max(0, Math.min(100, demand)) / 100 : 0;
        bar.setAttribute("width", String(share * full));
      }
      const info = root.querySelector(`[data-info="${id}"]`);
      if (info) info.innerHTML = this._roomInfo(climate, off, sensorFault);
    }
    const rows = this._layoutRows || [];
    rows.forEach((row, r) => {
      const airing = this._state(row.ventilation);
      const on = airing?.state === "on";
      root.querySelector(`[data-band="${r}"]`)?.setAttribute("class", `band${on ? " on" : ""}`);
      const label = root.querySelector(`[data-floor="${r}"]`);
      if (!label || !row.floor) return;
      label.textContent = on ? `${row.floor} · ${t.airing} ${airing.attributes.ends || ""}`.trim()
        : row.floor;
      label.classList.toggle("airing", on);
    });
    const rowFlows = rows.map((row, r) => row.rooms.map((_, i) => flowing[`${r}-${i}`]));
    rowFlows.forEach((flows, r) => {
      flows.forEach((_, i) => {
        const beyond = flows.slice(i).some(Boolean);
        this._flow(`main-s-${r}-${i}`, beyond, slow);
        this._flow(`main-r-${r}-${i}`, beyond, slow);
      });
      // The lowest riser segment always runs with the pump (bypass); upper ones
      // only while a room on their floor or above takes water.
      const above = rowFlows.slice(0, r + 1).some((f) => f.some(Boolean));
      const on = pump && (above || r === rows.length - 1);
      this._flow(`riser-s-${r}`, on, slow);
      this._flow(`riser-r-${r}`, on, slow);
    });
    for (const id of Object.keys(flowing)) {
      this._flow(`branch-s-${id}`, flowing[id], slow);
      this._flow(`branch-r-${id}`, flowing[id], slow);
    }

    const fault = code.startsWith("fault") || boiler?.attributes?.flow_check === "no_heat";
    root.querySelector("[data-boiler]")?.setAttribute("class",
      `boiler${burning ? " burning" : ""}${fault ? " fault" : ""}`);
    const temp = root.querySelector("[data-boiler-temp]");
    if (temp) temp.textContent = cfg.flow ? this._format(cfg.flow) : "";
    const state = root.querySelector("[data-boiler-state]");
    if (state) state.textContent = fault ? t.fault : burning ? t.running : t.stopped;
    const outdoor = root.querySelector("[data-outdoor]");
    if (outdoor) outdoor.textContent = cfg.outdoor ? this._format(cfg.outdoor) : "";

    // Nothing is switched: shadow mode, or the demo with its virtual outputs.
    const banner = cfg.demo ? t.demo : this._state(cfg.shadow)?.state === "on" ? t.shadow : "";
    const bannerEl = root.querySelector("[data-banner]");
    if (bannerEl) {
      bannerEl.hidden = !banner;
      bannerEl.textContent = banner;
    }
    root.querySelector("ha-card")?.classList.toggle("has-banner", Boolean(banner));

    // Phase bar and the hold or block next to it.
    const step = STEP[code] || "idle";
    root.querySelectorAll("[data-step]").forEach((el) => {
      el.classList.toggle("active", el.dataset.step === step);
      if (el.dataset.step === "valves") {
        el.textContent = code === "pre_close" ? t.pre_close : code === "pre_open" ? t.pre_open
          : t.phases.valves;
      }
    });
    const chip = root.querySelector("[data-chip]");
    if (chip) {
      const blocked = BLOCKS.has(code) || code === "min_on_hold";
      chip.hidden = !blocked;
      chip.classList.toggle("fault", code.startsWith("fault"));
      chip.textContent = blocked ? this._format(cfg.reason) : "";
    }
    const sl = root.querySelector("[data-sl]");
    if (sl) {
      sl.style.setProperty("--sl", fault ? "var(--error-color, #db4437)" : STEP_COLORS[step]);
      sl.querySelector("[data-sl-title]").textContent = this._format(cfg.reason);
    }
    const nowEl = root.querySelector("[data-now]");
    if (nowEl) {
      const lines = reason?.attributes?.now || [reason?.attributes?.detail || ""];
      nowEl.innerHTML = lines.filter(Boolean).map((line) => `<p>${esc(line)}</p>`).join("");
    }
    const nextEl = root.querySelector("[data-next]");
    if (nextEl) {
      const items = (reason?.attributes?.upcoming || []).slice(0, options(cfg).upcomingMax);
      nextEl.innerHTML = items.length
        ? items.map((item) => `<li>${esc(item.text)}</li>`).join("")
        : `<li>${esc(t.nothing_next)}</li>`;
    }
    this._tick();
  }

  // The line under the room: temperature and its target, or off; a faulty sensor.
  _roomInfo(climate, off, sensorFault) {
    const t = this._t;
    const cur = climate?.attributes?.current_temperature;
    const target = climate?.attributes?.temperature;
    const parts = [];
    if (off) parts.push(esc(t.off));
    else if (cur != null) {
      parts.push(`${this._num(cur)}${target != null ? ` → ${this._num(target)}` : ""} °C`);
    }
    if (!off && climate?.state === "heat") parts.push(esc(t.manual));
    if (sensorFault) parts.push(`<tspan class="warn">${esc(t.sensor)}</tspan>`);
    return parts.join(" · ");
  }

  _num(value) {
    const lang = this._hass?.locale?.language || this._hass?.language || undefined;
    return Number(value).toLocaleString(lang, { maximumFractionDigits: 1 });
  }

  _flow(id, on, slow) {
    const el = this.shadowRoot.querySelector(`[data-flow="${id}"]`);
    if (!el) return;
    el.classList.toggle("on", Boolean(on));
    el.classList.toggle("slow", Boolean(on && slow));
  }

  _countdown() {
    const reason = this._state(this._config.reason);
    const code = reason?.state;
    let key = COUNTDOWN[code];
    let until = reason?.attributes?.until;
    if (STEP[code] === "firing" && !key) {
      // Firing on demand: the end of the minimum run, else the duty stop.
      const minOn = (reason?.attributes?.upcoming || []).find((e) => e.kind === "min_on_end");
      if (minOn) {
        key = "min_on";
        until = minOn.at;
      } else if (until) {
        key = "duty";
      }
    }
    const left = until ? (new Date(until).getTime() - Date.now()) / 1000 : NaN;
    return key && left > 0 ? this._t.countdown[key].replace("{t}", clock(left)) : "";
  }

  _tick() {
    const root = this.shadowRoot;
    if (!root || !this._hass || !this._config) return;
    const text = this._countdown();
    const countdown = root.querySelector("[data-countdown]");
    if (countdown) countdown.textContent = text;
    const slText = root.querySelector("[data-sl-text]");
    if (slText) slText.textContent = text;
  }
}

// Editor fields -> keys of `options()`.
const FIELDS = {
  layout: "layout",
  show_now: "now",
  show_upcoming: "upcoming",
  upcoming_max: "upcomingMax",
  show_phases: "phases",
  show_status: "status",
  show_outdoor: "outdoor",
  interactive: "interactive",
  tap_action: "tapAction",
};

/*
 * Visual editor of the display options. The entities and floors stay as the
 * generator wrote them; the editor only changes the options.
 */
class HydronicHeatingFlowCardEditor extends HTMLElement {
  setConfig(config) {
    this._config = config || {};
    this._render();
  }

  set hass(hass) {
    this._hass = hass;
    this._render();
  }

  get _t() {
    const lang = (this._hass?.locale?.language || this._hass?.language || "en").slice(0, 2);
    return (TEXTS[lang] || TEXTS.en).editor;
  }

  _render() {
    if (!this._config || !this._hass) return;
    if (!this._form) {
      this._note = document.createElement("p");
      this._note.style.cssText = "margin: 0 0 12px; color: var(--secondary-text-color);";
      this._form = document.createElement("ha-form");
      this._form.computeLabel = (schema) => this._t[schema.name] || schema.name;
      this._form.addEventListener("value-changed", (ev) => this._changed(ev.detail.value || {}));
      this.append(this._note, this._form);
    }
    const t = this._t;
    const opt = options(this._config);
    this._note.textContent = t.entities;
    this._note.hidden = Array.isArray(this._config.floors) && this._config.floors.length > 0;
    this._data = { title: this._config.title || "" };
    for (const [field, key] of Object.entries(FIELDS)) this._data[field] = opt[key];
    this._form.hass = this._hass;
    this._form.data = this._data;
    this._form.schema = [
      { name: "title", selector: { text: {} } },
      {
        name: "layout",
        selector: {
          select: {
            mode: "dropdown",
            options: [
              { value: "full", label: t.full },
              { value: "compact", label: t.compact },
            ],
          },
        },
      },
      {
        type: "grid",
        name: "",
        schema: [
          "show_now", "show_upcoming", "show_phases", "show_status", "show_outdoor", "interactive",
        ].map((name) => ({
          name,
          selector: { boolean: {} },
        })),
      },
      { name: "upcoming_max", selector: { number: { min: 1, max: 8, mode: "box" } } },
      { name: "tap_action", selector: { ui_action: { default_action: "none" } } },
    ];
  }

  _changed(value) {
    // Only the changed fields go to the config, and a value equal to its
    // default is left out, so the YAML stays short.
    const config = { ...this._config };
    for (const field of new Set([...Object.keys(this._data), ...Object.keys(value)])) {
      const val = value[field];
      if (val === this._data[field] || (val == null && this._data[field] == null)) continue;
      delete config[field];
      if (field === "title") {
        if (val) config.title = val;
      } else if (field === "tap_action") {
        // "Nothing" is the default of the card, so it is left out.
        if (options({ tap_action: val }).tapAction) config.tap_action = val;
      } else if (FIELDS[field] && val != null && val !== "" && val !== options(config)[FIELDS[field]]) {
        config[field] = val;
      }
    }
    this._config = config;
    this.dispatchEvent(
      new CustomEvent("config-changed", { detail: { config }, bubbles: true, composed: true }),
    );
    this._render();
  }
}

// The editor of the built-in button card brings ha-form with it.
async function loadForm() {
  if (customElements.get("ha-form")) return;
  try {
    await customElements.get("hui-button-card")?.getConfigElement();
  } catch (err) {
    // Without ha-form the card still works from YAML.
  }
}

// Display options with their defaults (FR-UI-25). A part's own switch wins over
// `show_text`, which wins over the layout; compact shows a state line instead of
// the texts and the phase bar.
function options(config) {
  const cfg = config || {};
  const layout = cfg.layout === "compact" ? "compact" : "full";
  const flag = (value, fallback) => (typeof value === "boolean" ? value : fallback);
  const text = flag(cfg.show_text, layout === "full");
  const max = Number(cfg.upcoming_max);
  return {
    layout,
    now: flag(cfg.show_now, text),
    upcoming: flag(cfg.show_upcoming, text),
    phases: flag(cfg.show_phases, layout === "full"),
    status: flag(cfg.show_status, layout === "compact"),
    outdoor: flag(cfg.show_outdoor, true),
    upcomingMax: Number.isInteger(max) && max > 0 ? max : undefined,
    interactive: flag(cfg.interactive, true),
    tapAction: cfg.tap_action?.action && cfg.tap_action.action !== "none" ? cfg.tap_action : undefined,
  };
}

function clock(seconds) {
  const s = Math.max(0, Math.round(seconds));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const rest = String(s % 60).padStart(2, "0");
  return h ? `${h}:${String(m).padStart(2, "0")}:${rest}` : `${m}:${rest}`;
}

function clip(text, max) {
  return text.length > max ? `${text.slice(0, Math.max(1, max - 1))}…` : text;
}

function esc(value) {
  return String(value).replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[c]);
}

// The card may load twice (a Lovelace resource and an extra module of an older
// version): each element is defined once and the card picker lists it once.
function defineOnce(tag, element) {
  if (customElements.get(tag)) return false;
  customElements.define(tag, element);
  return true;
}

