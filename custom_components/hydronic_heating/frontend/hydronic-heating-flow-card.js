/*
 * Heating Controller – animated scheme (FR-UI-25).
 *
 * Shows the boiler, the supply and return pipes and the radiators of the rooms
 * by floor. Water flows only where it really flows, a phase bar shows Idle ->
 * Valves -> Boiler heats -> Overrun with a countdown, and two short texts say
 * what happens now and next. One colour has one meaning:
 * - a bright radiator has water flowing now, a faded one still gives heat (it
 *   fades out within 30 minutes after the flow); the pipe temperature is only a
 *   number next to the valve,
 * - the valve is a ball valve: the lever along the pipe is open, across it is
 *   closed, it turns while the valve moves; cyan = open with water flowing, an
 *   empty ring = open without current at rest, grey = closed,
 * - an orange frame, a flame and the demand bar mark a room that calls the
 *   boiler; red marks faults; a window icon and a cyan band mark airing,
 * - a striped band says that the control switches nothing (shadow or demo).
 *
 * The card is served by the integration and generated by the service
 * `hydronic_heating.generate_dashboard`, which fills in the entities.
 * Animations use CSS only and stop with prefers-reduced-motion.
 *
 * Options (FR-UI-25): `layout: compact` is lower and without the texts,
 * `show_text`, `show_now`, `show_upcoming`, `upcoming_max`, `show_phases` and
 * `show_outdoor` hide parts, `show_status` is the one-line state of the compact
 * layout, `interactive: false` makes the parts not
 * clickable and `tap_action` is a standard action of the whole card. The
 * defaults keep the full, clickable scheme.
 */

